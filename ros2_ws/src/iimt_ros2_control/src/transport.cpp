// Общие типы суставов, конфигурация и абстрактный транспорт.
#include "iimt_ros2_control/core.hpp"
// Макрос offsetof для проверки расположения полей ABI.
#include <cstddef>
// POSIX-функции динамической загрузки библиотеки SDK.
#include <dlfcn.h>
// Умный указатель для владения транспортом.
#include <memory>
// Сохраняем текущую упаковку структур до подключения заголовка производителя.
#pragma pack(push)
// Подключаем объявления SDK, включая его настройки упаковки структур.
#include "robotapi.h"
// Восстанавливаем упаковку, чтобы заголовок SDK не изменил последующие структуры C++.
#pragma pack(pop)
// На этапе компиляции требуем 64-битный тип дескриптора SDK.
static_assert(sizeof(JTRHD) == 8, "SDK requires 64-bit Linux ABI");
// Проверяем размеры структур углов и параметров ServoJ против ABI производителя.
static_assert(sizeof(JointRad) == 48 && sizeof(ServojParam) == 68,
              // При несовпадении размеров сборка останавливается с этой диагностикой.
              "vendor ABI mismatch");
// Проверяем смещение периода ServoJ внутри упакованной структуры.
static_assert(offsetof(ServojParam, t) == 56, "vendor ABI offset mismatch");
// Открываем пространство имён аппаратного интерфейса.
namespace iimt_ros2_control {
// Конкретный транспорт SDK без дальнейшего наследования.
class SdkTransport final : public Transport {
  // Дескриптор загруженной библиотеки; nullptr означает, что библиотека не открыта.
  void *library_{nullptr};
  // Отдельные подключения SDK для чтения, ServoJ и управляющих операций; это не гарантия потокобезопасности.
  JTRHD state_{0}, servo_{0}, control_{0};
  // Указатель подключения имеет точную сигнатуру API_Login из заголовка SDK.
  decltype(&API_Login) login_{};
  // Указатель освобождения подключения SDK.
  decltype(&API_Logout) logout_{};
  // Указатель синхронного чтения углов суставов.
  decltype(&API_GetRobotJointRad) read_{};
  // Указатель отправки параметров ServoJ.
  decltype(&API_Servoj) send_{};
  // Указатель команды остановки робота.
  decltype(&API_Stop) stop_{};
  // Указатель очистки незавершённой траектории.
  decltype(&API_ClearUnfinishedTrajectory) clear_{};
  // Шаблон загрузки функции SDK по имени с требуемым типом указателя.
  template <class T> T symbol(const char *name) {
    // Ищем адрес символа в ранее открытой библиотеке.
    auto p = dlsym(library_, name);
    // Отсутствующий символ делает выбранную библиотеку непригодной.
    if (!p)
      // Сообщаем имя функции, которую библиотека не экспортирует.
      throw std::runtime_error(std::string("SDK missing symbol ") + name);
    // Преобразуем адрес символа в тип указателя функции SDK.
    return reinterpret_cast<T>(p);
    // Завершаем поиск и типизацию символа.
  }

  // Открываем реализацию публичных операций транспорта.
public:
  // Деструктор освобождает загрузку библиотеки; соединения закрываются отдельным disconnect.
  ~SdkTransport() override {
    // Проверяем, была ли библиотека успешно загружена.
    if (library_)
      // Уменьшаем счётчик ссылок динамического загрузчика на библиотеку.
      dlclose(library_);
    // Завершаем уничтожение транспорта.
  }
  // Загружаем SDK и открываем три подключения к одному роботу.
  bool connect(const Config &c) override {
    // Немедленно разрешаем зависимости библиотеки и не экспортируем её символы глобально.
    library_ = dlopen(c.sdk_library_path.c_str(), RTLD_NOW | RTLD_LOCAL);
    // Проверяем результат открытия файла библиотеки.
    if (!library_)
      // Передаём текст ошибки динамического загрузчика вызывающему коду.
      throw std::runtime_error(dlerror());
    // Загружаем функцию подключения SDK.
    login_ = symbol<decltype(login_)>("API_Login");
    // Загружаем функцию закрытия подключения.
    logout_ = symbol<decltype(logout_)>("API_Logout");
    // Загружаем функцию чтения измеренных углов.
    read_ = symbol<decltype(read_)>("API_GetRobotJointRad");
    // Загружаем функцию отправки ServoJ.
    send_ = symbol<decltype(send_)>("API_Servoj");
    // Загружаем функцию остановки.
    stop_ = symbol<decltype(stop_)>("API_Stop");
    // Загружаем функцию очистки очереди траектории производителя.
    clear_ = symbol<decltype(clear_)>("API_ClearUnfinishedTrajectory");
    // Открываем подключение чтения; при неудаче остальные Login не выполняются.
    return login_(c.robot_ip.c_str(), c.port, state_) &&
           // После успеха чтения открываем подключение команд ServoJ.
           login_(c.robot_ip.c_str(), c.port, servo_) &&
           // После двух успешных подключений открываем управляющее; возвращаем общий успех.
           login_(c.robot_ip.c_str(), c.port, control_);
    // Завершаем подключение транспорта.
  }
  // Синхронно читаем измеренные углы через SDK в массив вызывающего кода.
  bool read(Joints &q) override {
    // Обнуляем структуру результата перед передачей в SDK.
    JointRad p{};
    // Вызываем чтение на подключении состояния и проверяем код возврата.
    if (!read_(state_, &p))
      // При ошибке не копируем неподтверждённые данные в выходной массив.
      return false;
    // Перебираем шесть осей в исходном порядке SDK.
    for (size_t i = 0; i < 6; ++i)
      // Копируем измеренный угол в радианах в массив интерфейса.
      q[i] = p.robotRad[i];
    // Сообщаем об успешном чтении всех углов.
    return true;
    // Завершаем операцию чтения состояния.
  }
  // Отправляем одну целевую позицию с текущими настройками ServoJ.
  bool send(const Joints &q, const Config &c) override {
    // Обнуляем структуру команды, включая все поля до их заполнения.
    ServojParam p{};
    // Перебираем шесть заданных суставов.
    for (size_t i = 0; i < 6; ++i)
      // Копируем угол в поле SDK, преобразуя тип согласно объявлению производителя.
      p.q[i] = q[i];
    // Передаём параметр ускорения a без дополнительного масштабирования.
    p.a = c.servo_a;
    // Передаём параметр скорости v из конфигурации.
    p.v = c.servo_v;
    // Передаём длительность ServoJ t в секундах.
    p.t = c.period;
    // Передаём настроенное время упреждения в секундах.
    p.lookahead_time = c.lookahead_time;
    // Передаём коэффициент gain без предположений о значении нуля у производителя.
    p.gain = c.gain;
    // Возвращаем успех вызова SDK; он сам по себе не подтверждает физическое выполнение движения.
    return send_(servo_, &p) != 0;
    // Завершаем отправку одной команды ServoJ.
  }
  // Запрашиваем остановку и очистку незавершённой траектории через управляющее подключение.
  bool stop() override {
    // Проверяем наличие управляющего дескриптора.
    if (!control_)
      // Без управляющего подключения возвращаем успех без вызова SDK; это не подтверждение физической остановки.
      return true;
    // Вызываем Stop, только если адрес функции загружен, и запоминаем результат.
    const bool stopped = stop_ && stop_(control_);
    // Независимо от успеха Stop пытаемся очистить незавершённую траекторию.
    const bool cleared = clear_ && clear_(control_);
    // Успех операции требует успешных Stop и Clear.
    return stopped && cleared;
    // Завершаем запрос остановки и очистки.
  }
  // Закрываем все открытые подключения SDK.
  void disconnect() override {
    // Накапливаем общий результат Logout, не прекращая обход после первой ошибки.
    bool ok = true;
    // Закрытие возможно только после загрузки функции Logout.
    if (logout_) {
      // Обходим дескрипторы команд, состояния и управления по адресам для их обнуления.
      for (auto *handle : {&servo_, &state_, &control_}) {
        // Нулевой дескриптор не требует вызова Logout.
        if (*handle) {
          // Запрашиваем освобождение конкретного подключения.
          if (logout_(*handle))
            // Обнуляем дескриптор только после подтверждённого SDK успеха.
            *handle = 0;
          // Если SDK отверг Logout, оставляем дескриптор для диагностики состояния.
          else
            // Запоминаем ошибку, продолжая закрывать остальные подключения.
            ok = false;
          // Завершаем обработку одного открытого дескриптора.
        }
        // Завершаем обход трёх подключений.
      }
      // Завершаем ветку доступной функции Logout.
    }
    // Проверяем, были ли неподтверждённые операции закрытия.
    if (!ok)
      // Явно сообщаем ошибку освобождения соединения, не скрывая её от вызывающего кода.
      throw std::runtime_error("API_Logout failed; remote connection cleanup not confirmed");
    // Завершаем закрытие подключений SDK.
  }
  // Завершаем реализацию транспорта производителя.
};
// Фабрика возвращает транспорт через абстрактный интерфейс.
std::unique_ptr<Transport> make_transport() {
  // Создаём реализацию с единственным владельцем; соединения пока не открываются.
  return std::make_unique<SdkTransport>();
  // Завершаем фабрику транспорта.
}
// namespace iimt_ros2_control // Закрываем пространство имён аппаратного интерфейса.
} // namespace iimt_ros2_control
